function events = llc_extract_gate_events(gateTimes, gateValues)
    % LLC_EXTRACT_GATE_EVENTS Preserve exact applied-gate change times.
    gateTimes = gateTimes(:);
    if isempty(gateTimes) || ~isnumeric(gateTimes) || any(~isfinite(gateTimes)) || ...
            any(diff(gateTimes) <= 0) || size(gateValues, 1) ~= numel(gateTimes) || ...
            size(gateValues, 2) ~= 4 || any(~isfinite(gateValues), 'all') || ...
            any(gateValues ~= 0 & gateValues ~= 1, 'all')
        error('llc:InvalidGateLog', ...
              'Gate log must have increasing finite times and four binary channels.');
    end
    gateValues = uint8(gateValues);
    changed = any(gateValues(2:end, :) ~= gateValues(1:end-1, :), 2);
    eventRows = find([false; changed]);
    events = struct('initial_gate_values', gateValues(1, :), ...
                    'gate_event_times_s', gateTimes(eventRows), ...
                    'gate_values_after', gateValues(eventRows, :));
end
