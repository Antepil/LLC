function result = llc_run_independent_closed_loop( ...
        model, hardware, modelFile, experiment, control, steadyConfig, solver, sampling, metricConfig)
    % LLC_RUN_INDEPENDENT_CLOSED_LOOP Compare independent plant and Neural ODE loops.
    validateInputs(experiment, sampling);
    step = 1 / (double(sampling.reference_frequency_hz) * ...
                double(sampling.intervals_per_cycle));
    startupMode = string(experiment.startup.mode);
    evaluationDuration = double(experiment.startup.evaluation_duration_s);

    if startupMode == "cold"
        evaluationStart = 0;
        vinSignal = experiment.vin;
        referenceSignal = experiment.reference;
    else
        evaluationStart = double(experiment.startup.preheat_duration_s);
        vinSignal = stagedSignal(evaluationStart, experiment.preheat_vin, experiment.vin);
        referenceSignal = stagedSignal(evaluationStart, ...
                                       experiment.preheat_reference, experiment.reference);
    end
    evaluationTimes = fixedGrid(evaluationStart, evaluationDuration, step);
    referenceTimes = fixedGrid(0, evaluationStart + evaluationDuration, step);
    referenceBranch = llc_simulate_reference_closed_loop(hardware, modelFile, zeros(1, 4), ...
        referenceTimes, vinSignal, referenceSignal, control, solver);

    steadyAssessment = [];
    if startupMode == "cold"
        initialState = zeros(4, 1);
        controllerState = llc_initialize_closed_loop_controller(control);
    else
        steadyAssessment = assessPreheat(referenceBranch, experiment, steadyConfig, ...
                                         referenceSignal, evaluationStart);
        initialState = interp1(referenceBranch.raw_state_times_s, ...
            referenceBranch.raw_state_values, evaluationStart, 'linear').';
        reconstruction = llc_reconstruct_closed_loop_controller( ...
            referenceBranch.raw_state_times_s, referenceBranch.raw_state_values(:, 4), ...
            referenceBranch.initial_gate_values, referenceBranch.gate_event_times_s, ...
            referenceBranch.gate_values_after, referenceSignal, control, evaluationStart, ...
            solver.event_time_tolerance_s);
        controllerState = reconstruction.final_state;
    end

    neuralBranch = llc_simulate_neural_closed_loop(model, initialState, controllerState, ...
        evaluationTimes, vinSignal, referenceSignal, control, solver);
    referenceStates = interp1(referenceBranch.times_s, referenceBranch.states, ...
                              evaluationTimes, 'linear');
    stateMetrics = llc_compute_neural_ode_metrics(evaluationTimes, neuralBranch.states, ...
        referenceStates, model.state_scales, metricConfig);
    target = llc_evaluate_validation_signal(referenceSignal, evaluationTimes);
    tracking = struct( ...
        'reference_plant_rmse_v', sqrt(mean((referenceStates(:, 4) - target) .^ 2)), ...
        'neural_ode_rmse_v', sqrt(mean((neuralBranch.states(:, 4) - target) .^ 2)), ...
        'reference_plant_mean_absolute_error_v', mean(abs(referenceStates(:, 4) - target)), ...
        'neural_ode_mean_absolute_error_v', mean(abs(neuralBranch.states(:, 4) - target)));
    result = struct( ...
        'startup_mode', char(startupMode), ...
        'times_s', evaluationTimes, ...
        'evaluation_times_s', evaluationTimes - evaluationStart, ...
        'reference_states', referenceStates, ...
        'predicted_states', neuralBranch.states, ...
        'reference_voltage_v', target, ...
        'state_metrics', stateMetrics, ...
        'tracking_metrics', tracking, ...
        'steady_state_assessment', steadyAssessment, ...
        'reference_branch', referenceBranch, ...
        'neural_branch', neuralBranch);
end

function assessment = assessPreheat(branch, experiment, config, referenceSignal, handoffTime)
    if ~isstruct(config) || isempty(fieldnames(config))
        error('llc:InvalidSteadyStateConfig', ...
              'Warm startup requires steady-state assessment configuration.');
    end
    config.check_times_s = handoffTime;
    preheatReference = llc_evaluate_validation_signal(referenceSignal, ...
        max(0, handoffTime - 64 * eps(max(handoffTime, 1))));
    assessment = llc_assess_periodic_steady_state( ...
        branch.raw_state_times_s, branch.raw_state_values, ...
        branch.raw_gate_times_s, branch.raw_gate_values, preheatReference, config);
    if experiment.startup.require_steady_state && ~assessment.settled
        error('llc:PreheatNotSettled', ...
              'Reference plant was not settled at the configured warm-start handoff.');
    end
end

function signal = stagedSignal(switchTime, before, after)
    signal = struct('type', 'staged', 'switch_time_s', switchTime, ...
                    'before', before, 'after', after);
end

function times = fixedGrid(startTime, duration, step)
    intervals = duration / step;
    count = round(intervals);
    tolerance = 128 * eps(max(abs(intervals), 1));
    if abs(intervals - count) > tolerance
        error('llc:InvalidComparisonGrid', ...
              'Duration must be an integer multiple of the comparison interval.');
    end
    times = startTime + (0:count).' * step;
    times(end) = startTime + duration;
end

function validateInputs(experiment, sampling)
    required = {'startup', 'vin', 'reference'};
    if ~isstruct(experiment) || ~isscalar(experiment) || ~all(isfield(experiment, required)) || ...
            ~isstruct(experiment.startup) || ...
            ~all(isfield(experiment.startup, {'mode', 'evaluation_duration_s'})) || ...
            ~ismember(string(experiment.startup.mode), ["cold", "warm"]) || ...
            ~isscalar(experiment.startup.evaluation_duration_s) || ...
            ~isfinite(experiment.startup.evaluation_duration_s) || ...
            experiment.startup.evaluation_duration_s <= 0
        error('llc:InvalidValidationInput', 'Independent closed-loop experiment is invalid.');
    end
    if ~isstruct(sampling) || ~all(isfield(sampling, ...
            {'reference_frequency_hz', 'intervals_per_cycle'})) || ...
            any(~isfinite([sampling.reference_frequency_hz, sampling.intervals_per_cycle])) || ...
            sampling.reference_frequency_hz <= 0 || sampling.intervals_per_cycle <= 0 || ...
            sampling.intervals_per_cycle ~= round(sampling.intervals_per_cycle)
        error('llc:InvalidValidationInput', 'Comparison sampling is invalid.');
    end
    if string(experiment.startup.mode) == "warm" && ...
            (~all(isfield(experiment.startup, ...
                {'preheat_duration_s', 'require_steady_state'})) || ...
             ~all(isfield(experiment, {'preheat_vin', 'preheat_reference'})))
        error('llc:InvalidValidationInput', 'Warm startup configuration is incomplete.');
    end
end
