function state = llc_initialize_closed_loop_controller(control)
    % LLC_INITIALIZE_CLOSED_LOOP_CONTROLLER Match the existing PFM S-function state.
    validateControl(control);
    state = struct( ...
        'phase_rad', 0, 'integral_v_s', 0, 'filtered_voltage_v', 0, ...
        'frequency_hz', control.initial_frequency_hz, ...
        'reference_voltage_v', 0, 'error_v', 0, 'last_time_s', 0, ...
        'reference_ramp_elapsed_time_s', 0, ...
        'next_control_time_s', 0, ...
        'next_edge_time_s', 0.5 / control.initial_frequency_hz, ...
        'pending_on_time_s', control.deadtime_s, ...
        'active_pair', 0, 'pending_pair', 1, 'desired_pair', 1);
end

function validateControl(control)
    required = {'control_period_s', 'voltage_filter_time_constant_s', ...
        'reference_ramp_time_s', 'initial_frequency_hz', 'bias_frequency_hz', ...
        'frequency_slew_rate_hz_per_s', 'proportional_gain_hz_per_v', ...
        'integral_gain_hz_per_v_s', 'deadtime_s', 'minimum_pulse_s'};
    if ~isstruct(control) || ~isscalar(control) || ~all(isfield(control, required))
        error('llc:InvalidControl', 'Control configuration is incomplete.');
    end
    for index = 1:numel(required)
        value = control.(required{index});
        if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value) || value <= 0
            error('llc:InvalidControl', '%s must be finite and positive.', required{index});
        end
    end
    if isfield(control, 'minimum_frequency_hz') || isfield(control, 'maximum_frequency_hz')
        error('llc:InvalidControl', 'Frequency bounds are unsupported by this validation contract.');
    end
end
