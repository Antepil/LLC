function llc_validate_closed_loop_controller_state(state, control)
    % LLC_VALIDATE_CLOSED_LOOP_CONTROLLER_STATE Validate a complete PI/PFM state.
    required = {'phase_rad', 'integral_v_s', 'filtered_voltage_v', ...
        'frequency_hz', 'reference_voltage_v', 'error_v', 'last_time_s', ...
        'reference_ramp_elapsed_time_s', 'next_control_time_s', ...
        'next_edge_time_s', 'pending_on_time_s', 'active_pair', ...
        'pending_pair', 'desired_pair'};
    if ~isstruct(state) || ~isscalar(state) || ~all(isfield(state, required)) || ...
            ~isstruct(control) || ~isscalar(control) || ...
            ~all(isfield(control, {'reference_ramp_time_s', 'deadtime_s', ...
                                   'minimum_pulse_s'}))
        error('llc:InvalidControllerState', ...
              'Controller state or control configuration is incomplete.');
    end
    finiteFields = {'phase_rad', 'integral_v_s', 'filtered_voltage_v', ...
        'frequency_hz', 'reference_voltage_v', 'error_v', 'last_time_s', ...
        'reference_ramp_elapsed_time_s', 'next_control_time_s', ...
        'next_edge_time_s', 'active_pair', 'pending_pair', 'desired_pair'};
    for index = 1:numel(finiteFields)
        value = state.(finiteFields{index});
        if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ~isfinite(value)
            error('llc:InvalidControllerState', ...
                  'Controller state field %s must be a finite real scalar.', ...
                  finiteFields{index});
        end
    end
    pendingOn = state.pending_on_time_s;
    if ~isnumeric(pendingOn) || ~isreal(pendingOn) || ~isscalar(pendingOn) || ...
            isnan(pendingOn) || pendingOn == -Inf
        error('llc:InvalidControllerState', ...
              'pending_on_time_s must be finite or positive infinity.');
    end
    if state.frequency_hz <= 0 || state.reference_voltage_v < 0 || ...
            state.last_time_s < 0 || state.reference_ramp_elapsed_time_s < 0
        error('llc:InvalidControllerState', ...
              'Controller frequency, time and reference fields are invalid.');
    end
    scheduleTolerance = max(1e-14, 32 * eps(max(state.last_time_s, control.deadtime_s)));
    scheduled = [state.next_control_time_s, state.next_edge_time_s];
    if any(scheduled < state.last_time_s - scheduleTolerance) || ...
            (~isinf(pendingOn) && pendingOn < state.last_time_s - scheduleTolerance)
        error('llc:InvalidControllerState', ...
              'Controller contains an event scheduled before its current time.');
    end
    if ~ismember(state.active_pair, [0, 1, 2]) || ...
            ~ismember(state.pending_pair, [0, 1, 2]) || ...
            ~ismember(state.desired_pair, [1, 2]) || ...
            any([state.active_pair, state.pending_pair, state.desired_pair] ~= ...
                round([state.active_pair, state.pending_pair, state.desired_pair]))
        error('llc:InvalidControllerState', 'Controller bridge-pair state is invalid.');
    end
end
