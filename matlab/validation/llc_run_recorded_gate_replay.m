function result = llc_run_recorded_gate_replay(model, trajectoryInput, solver, metricConfig)
    % LLC_RUN_RECORDED_GATE_REPLAY Free-roll the model with recorded exact gates.
    if ischar(trajectoryInput) || (isstring(trajectoryInput) && isscalar(trajectoryInput))
        if ~isfile(trajectoryInput)
            error('llc:MissingValidationInput', 'Reference trajectory does not exist: %s', trajectoryInput);
        end
        trajectory = load(trajectoryInput);
    elseif isstruct(trajectoryInput) && isscalar(trajectoryInput)
        trajectory = trajectoryInput;
    else
        error('llc:InvalidValidationInput', 'trajectoryInput must be one MAT path or scalar struct.');
    end
    required = {'schema_version', 'trajectory_id', 'state_names', 'state_units', 'gate_names', ...
                'state_times_s', 'state_values', 'initial_gate_values', ...
                'gate_event_times_s', 'gate_values_after', 'raw_state_times_s', ...
                'raw_state_values', 'raw_gate_times_s', 'raw_gate_values', ...
                'raw_simulation_stop_time_s', 'effective_config', 'condition'};
    missing = required(~isfield(trajectory, required));
    if ~isempty(missing)
        error('llc:InvalidValidationInput', 'Reference trajectory is missing: %s', strjoin(missing, ', '));
    end
    validateTrajectoryContract(trajectory, solver.event_time_tolerance_s);
    if ~isfield(trajectory.condition, 'load_ohm') || ...
            ~isscalar(trajectory.condition.load_ohm) || ...
            ~isfinite(trajectory.condition.load_ohm) || trajectory.condition.load_ohm <= 0 || ...
            abs(trajectory.condition.load_ohm - model.load_resistance_ohm) > 1e-9
        error('llc:ModelContractMismatch', 'Reference trajectory load does not match model.');
    end
    vinSignal = trajectoryVin(trajectory);
    predicted = llc_integrate_neural_ode_events(model, trajectory.state_times_s, ...
        trajectory.state_values(1, :), trajectory.initial_gate_values, ...
        trajectory.gate_event_times_s, trajectory.gate_values_after, vinSignal, solver);
    metrics = llc_compute_neural_ode_metrics(trajectory.state_times_s, predicted, ...
        trajectory.state_values, model.state_scales, metricConfig);
    convergence = [];
    if isfield(solver, 'convergence_check') && solver.convergence_check.enabled
        refined = solver;
        refined.max_step_s = solver.max_step_s * solver.convergence_check.max_step_factor;
        refined.relative_tolerance = solver.relative_tolerance * solver.convergence_check.tolerance_factor;
        refined.absolute_tolerance = solver.absolute_tolerance * solver.convergence_check.tolerance_factor;
        refined.convergence_check.enabled = false;
        refinedStates = llc_integrate_neural_ode_events(model, trajectory.state_times_s, ...
            trajectory.state_values(1, :), trajectory.initial_gate_values, ...
            trajectory.gate_event_times_s, trajectory.gate_values_after, vinSignal, refined);
        convergence = struct('refined_solver', refined, ...
            'maximum_absolute_state_difference', max(abs(refinedStates - predicted), [], 1));
    end
    result = struct('mode', 'recorded_gate_replay', ...
                    'trajectory_id', char(string(trajectory.trajectory_id)), ...
                    'times_s', double(trajectory.state_times_s(:)), ...
                    'reference_states', double(trajectory.state_values), ...
                    'predicted_states', predicted, ...
                    'tail_window_s', metricConfig.tail_window_s, ...
                    'state_metrics', metrics, 'convergence', convergence);
end

function validateTrajectoryContract(trajectory, tolerance)
    if ~strcmp(char(string(trajectory.schema_version)), ...
               'llc-closed-loop-fixed-grid-trajectory-v3') || ...
            ~isequal(cellstr(string(trajectory.state_names(:))), ...
                     {'i_Lr'; 'v_Cr'; 'i_Lm'; 'v_o'}) || ...
            ~isequal(cellstr(string(trajectory.state_units(:))), {'A'; 'V'; 'A'; 'V'}) || ...
            ~isequal(cellstr(string(trajectory.gate_names(:))), ...
                     {'Q1_A_high'; 'Q2_A_low'; 'Q3_B_high'; 'Q4_B_low'})
        error('llc:InvalidValidationInput', ...
              'Reference trajectory schema or state/gate order is incompatible.');
    end
    fixedTimesInput = trajectory.state_times_s;
    fixedStatesInput = trajectory.state_values;
    validFixedTypes = isnumeric(fixedTimesInput) && isreal(fixedTimesInput) && ...
                      isvector(fixedTimesInput) && isnumeric(fixedStatesInput) && ...
                      isreal(fixedStatesInput);
    if ~validFixedTypes
        error('llc:InvalidValidationInput', ...
              'Reference fixed-grid state series must be real numeric data.');
    end
    times = double(fixedTimesInput(:));
    states = double(fixedStatesInput);
    fixedSteps = diff(times);
    if isempty(fixedSteps)
        fixedStep = NaN;
        fixedGridTolerance = NaN;
    else
        fixedStep = fixedSteps(1);
        fixedGridTolerance = 64 * eps(max(abs(times)));
    end
    if numel(times) < 2 || abs(times(1)) > tolerance || any(~isfinite(times)) || ...
            ~isfinite(fixedStep) || fixedStep <= 0 || ...
            any(abs(fixedSteps - fixedStep) > fixedGridTolerance) || ...
            ~isequal(size(states), [numel(times), 4]) || any(~isfinite(states), 'all')
        error('llc:InvalidValidationInput', 'Reference state series is invalid.');
    end
    rawStateTimesInput = trajectory.raw_state_times_s;
    rawStatesInput = trajectory.raw_state_values;
    if ~isnumeric(rawStateTimesInput) || ~isreal(rawStateTimesInput) || ...
            ~isvector(rawStateTimesInput) || ~isnumeric(rawStatesInput) || ...
            ~isreal(rawStatesInput)
        error('llc:InvalidValidationInput', ...
              'Raw state series must be real numeric data.');
    end
    rawStateTimes = double(rawStateTimesInput(:));
    rawStates = double(rawStatesInput);
    rawStop = trajectory.raw_simulation_stop_time_s;
    validRawStop = isnumeric(rawStop) && isreal(rawStop) && isscalar(rawStop) && ...
                   isfinite(rawStop) && rawStop > 0;
    if validRawStop
        stopTime = double(rawStop);
    else
        stopTime = NaN;
    end
    configuredStop = NaN;
    if isstruct(trajectory.effective_config) && isscalar(trajectory.effective_config) && ...
            isfield(trajectory.effective_config, 'generation') && ...
            isstruct(trajectory.effective_config.generation) && ...
            isfield(trajectory.effective_config.generation, 'simulation_stop_time_s')
        configuredValue = trajectory.effective_config.generation.simulation_stop_time_s;
        if isnumeric(configuredValue) && isreal(configuredValue) && ...
                isscalar(configuredValue) && isfinite(configuredValue) && configuredValue > 0
            configuredStop = double(configuredValue);
        end
    end
    if numel(rawStateTimes) < 2 || any(~isfinite(rawStateTimes)) || ...
            any(diff(rawStateTimes) <= 0) || ...
            ~isequal(size(rawStates), [numel(rawStateTimes), 4]) || ...
            any(~isfinite(rawStates), 'all') || ~validRawStop || ...
            abs(times(end) - stopTime) > tolerance || ...
            rawStateTimes(1) > times(1) || rawStateTimes(end) < times(end) || ...
            abs(rawStateTimes(end) - stopTime) > tolerance || ...
            ~isstruct(trajectory.effective_config) || ~isscalar(trajectory.effective_config) || ...
            ~isfield(trajectory.effective_config, 'generation') || ...
            ~isstruct(trajectory.effective_config.generation) || ...
            ~isfield(trajectory.effective_config.generation, 'simulation_stop_time_s') || ...
            ~isscalar(configuredStop) || ~isfinite(configuredStop) || configuredStop <= 0 || ...
            abs(configuredStop - stopTime) > tolerance || ...
            ~isfield(trajectory.effective_config, 'condition') || ...
            ~isstruct(trajectory.effective_config.condition)
        error('llc:InvalidValidationInput', ...
              'Raw state series, stop time or effective configuration is invalid.');
    end
    conditionFields = {'vin_v', 'load_ohm', 'reference_voltage_v'};
    for conditionIndex = 1:numel(conditionFields)
        name = conditionFields{conditionIndex};
        if ~isfield(trajectory.condition, name) || ...
                ~isfield(trajectory.effective_config.condition, name) || ...
                ~isnumeric(trajectory.condition.(name)) || ...
                ~isscalar(trajectory.condition.(name)) || ...
                ~isfinite(trajectory.condition.(name)) || trajectory.condition.(name) <= 0 || ...
                ~isnumeric(trajectory.effective_config.condition.(name)) || ...
                ~isscalar(trajectory.effective_config.condition.(name)) || ...
                ~isfinite(trajectory.effective_config.condition.(name)) || ...
                trajectory.effective_config.condition.(name) <= 0 || ...
                trajectory.condition.(name) ~= trajectory.effective_config.condition.(name)
            error('llc:InvalidValidationInput', ...
                  'Effective configuration condition differs from the saved trajectory.');
        end
    end
    reconstructedStates = interp1(rawStateTimes, rawStates, times, 'linear');
    stateTolerance = 1e-10 + 1e-10 .* abs(states);
    if any(~isfinite(reconstructedStates), 'all') || ...
            any(abs(reconstructedStates - states) > stateTolerance, 'all')
        error('llc:InvalidValidationInput', ...
              'Fixed-grid states do not reproduce the recorded raw state series.');
    end
    initial = uint8(trajectory.initial_gate_values);
    eventTimesInput = trajectory.gate_event_times_s;
    if ~isnumeric(eventTimesInput) || ~isreal(eventTimesInput) || ...
            (~isempty(eventTimesInput) && ~isvector(eventTimesInput))
        error('llc:InvalidValidationInput', ...
              'Reference gate-event times must be a real numeric vector.');
    end
    eventTimes = double(eventTimesInput(:));
    eventValues = uint8(trajectory.gate_values_after);
    if ~isequal(size(initial), [1, 4]) || any(double(trajectory.initial_gate_values) ~= 0 & ...
            double(trajectory.initial_gate_values) ~= 1, 'all') || ...
            ~isequal(size(eventValues), [numel(eventTimes), 4]) || ...
            any(~isfinite(eventTimes)) || any(diff(eventTimes) <= 0) || ...
            any(double(trajectory.gate_values_after) ~= 0 & ...
                double(trajectory.gate_values_after) ~= 1, 'all') || ...
            any(eventTimes <= times(1) + tolerance) || any(eventTimes > times(end) + tolerance)
        error('llc:InvalidValidationInput', 'Reference gate-event table is invalid or incomplete.');
    end
    allGateRows = [initial; eventValues];
    if any(allGateRows(:, 1) & allGateRows(:, 2)) || ...
            any(allGateRows(:, 3) & allGateRows(:, 4)) || ...
            any(~any(diff(double(allGateRows), 1, 1) ~= 0, 2))
        error('llc:InvalidValidationInput', 'Reference gate events violate bridge or change contracts.');
    end
    rawGateTimesInput = trajectory.raw_gate_times_s;
    if ~isnumeric(rawGateTimesInput) || ~isreal(rawGateTimesInput) || ...
            ~isvector(rawGateTimesInput)
        error('llc:InvalidValidationInput', ...
              'Raw applied-gate times must be a real numeric vector.');
    end
    rawTimes = double(rawGateTimesInput(:));
    rawValues = double(trajectory.raw_gate_values);
    if numel(rawTimes) < 2 || any(~isfinite(rawTimes)) || any(diff(rawTimes) <= 0) || ...
            ~isequal(size(rawValues), [numel(rawTimes), 4]) || ...
            any(~isfinite(rawValues), 'all') || any(rawValues ~= 0 & rawValues ~= 1, 'all') || ...
            rawTimes(1) > times(1) || rawTimes(end) < times(end) || ...
            any(rawValues(:, 1) & rawValues(:, 2)) || any(rawValues(:, 3) & rawValues(:, 4))
        error('llc:InvalidValidationInput', 'Raw applied-gate log is invalid or lacks coverage.');
    end
    extracted = llc_extract_gate_events(rawTimes, rawValues);
    if ~isequal(initial, extracted.initial_gate_values) || ...
            ~isequal(eventValues, extracted.gate_values_after) || ...
            numel(eventTimes) ~= numel(extracted.gate_event_times_s) || ...
            any(abs(eventTimes - extracted.gate_event_times_s) > tolerance)
        error('llc:InvalidValidationInput', ...
              'Gate-event table does not exactly reproduce the raw applied-gate log.');
    end
end

function signal = trajectoryVin(trajectory)
    if isfield(trajectory, 'state_excitation_names') && ...
            isfield(trajectory, 'state_excitation_values')
        names = string(trajectory.state_excitation_names(:));
        index = find(names == "vin_v", 1);
        if isempty(index)
            error('llc:InvalidValidationInput', 'Reference trajectory excitation omits vin_v.');
        end
        signal = struct('type', 'time_series', 'interpolation', 'linear', ...
            'times_s', double(trajectory.state_times_s(:)), ...
            'values_v', double(trajectory.state_excitation_values(:, index)));
    elseif isfield(trajectory.condition, 'vin_v')
        signal = struct('type', 'constant', 'value_v', double(trajectory.condition.vin_v));
    else
        error('llc:InvalidValidationInput', 'Reference trajectory does not define Vin.');
    end
end
